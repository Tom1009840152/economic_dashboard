function forexEntry(code: string): GlossaryEntry | undefined {
  if (!code.endsWith("CNY") || code === "CNY") return undefined;
  const currency = code.slice(0, -3);
  return {
    meaning: `1${currency}可兑换的人民币数量`,
    theory: FOREX_THEORY + (FOREX_NOTES[code] ?? ""),
  };
}

