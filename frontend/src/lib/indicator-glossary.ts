function bondEntry(code: string): GlossaryEntry | undefined {
  const m = /^(CN|US)_(2Y|5Y|10Y|30Y)$/.exec(code);
  if (!m) return undefined;
  const country = m[1] === "CN" ? "中国" : "美国";
  const maturity = BOND_MATURITY_LABEL[m[2]];
  return {
    meaning: `${country}${maturity}期国债到期收益率`,
    theory: BOND_YIELD_THEORY,
  };
}

export function getGlossaryEntry(code: string): GlossaryEntry | undefined {
  return BASE[code] ?? forexEntry(code) ?? bondEntry(code);
}
